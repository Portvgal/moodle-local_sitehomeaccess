namespace local_sitehomeaccess;

/**
 * Tests that Moodle can resolve the plugin capability label.
 *
 * @package    local_sitehomeaccess
 * @category   test
 * @copyright  2026 Portvgal
 * @license    http://www.gnu.org/copyleft/gpl.html GNU GPL v3 or later
 */
final class capability_string_test extends \advanced_testcase {
    /**
     * Test that the bypass capability has a human-readable label.
     */
    public function test_bypass_capability_label_is_available(): void {
        $this->assertSame(
            'Always access Site Home',
            get_capability_string('local/sitehomeaccess:bypass'),
        );
    }
}
